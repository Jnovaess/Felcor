import { hashPassword } from '../lib/password.mjs';
import { spawnSync } from 'node:child_process';
import { createInterface } from 'node:readline/promises';
import { Writable } from 'node:stream';
import { configureToolEnvironment } from './tool-environment.mjs';
configureToolEnvironment(process.cwd());
if (!process.stdin.isTTY) throw new Error('Execute em um terminal interativo privado.');
const muted = new Writable({write(chunk, encoding, done){done();}});
const reader = createInterface({input:process.stdin,output:muted,terminal:true});
console.log('Configura ADMIN_PASSWORD_HASH no Worker felcor. Não compartilhe a senha no chat.');
process.stdout.write('Nova senha (14–128 caracteres; entrada oculta): ');
const password = await reader.question('');
process.stdout.write('\nConfirme a senha: ');
const confirm = await reader.question('');
reader.close();process.stdout.write('\n');
if (password !== confirm) throw new Error('As senhas não coincidem.');
const hash = await hashPassword(password);
const result = spawnSync(process.execPath,['node_modules/wrangler/bin/wrangler.js','secret','put','ADMIN_PASSWORD_HASH','--name','felcor'],{input:hash+'\n',stdio:['pipe','inherit','inherit']});
if (result.error) throw result.error;
process.exit(result.status ?? 1);
